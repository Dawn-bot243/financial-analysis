export default function Glossary() {
  return (
    <details className="glossary">
      <summary>术语说明</summary>
      <dl>
        <dt>路径数</dt>
        <dd>
          蒙特卡洛模拟生成多少条未来路径。每条路径是一组完整的月度收益序列；
          路径越多，分位数和通过率越稳定，统计误差大致按 1/√N 缩小。
          快速试算可用 500–1,000 条，正式结果通常用 10,000 条。
        </dd>
        <dt>随机种子</dt>
        <dd>
          控制随机数序列的整数。相同种子 + 相同假设 + 相同代码，会得到完全相同的结果；
          改变种子只改变抽样噪声，不改变假设。对比情景时应保持种子相同。
        </dd>
        <dt>分位数</dt>
        <dd>
          把所有路径在同一时点的值从小到大排序后，处于 5%、25%、50%、75%、95% 位置的值。
          50% 是中位数；5%–95% 表示中间 90% 的路径范围。
        </dd>
        <dt>时间加权回撤</dt>
        <dd>
          剔除投入和赎回现金流影响后的组合净值，从历史高点到低点的最大跌幅。
          它衡量投资策略本身，不受你中途加钱、取钱的影响。
        </dd>
        <dt>联合通过率</dt>
        <dd>
          所有人生事件都按时足额支付的路径占比。单个事件通过率通常高于联合通过率。
        </dd>
        <dt>实际收益</dt>
        <dd>
          扣除通胀后的收益，按今日购买力表示。历史校准用官方全收益/财富指数，
          再按 2% 的通胀假设折算；当前系统没有单独的通胀层。
        </dd>
        <dt>全收益指数</dt>
        <dd>
          把分红按再投资计入的指数。当前权益用 CSI H00300/H00905/H00922、
          标普500 Total Return、Nasdaq XNDX、日经225 Total Return、恒生总收益指数；
          海外指数按中行汇率换算人民币、含汇率、未对冲。上证指数、日经225、
          恒生指数在官方全收益数据之前用对应 ETF 复权净值补长，标签为
          “官方TR + ETF补长”，不是纯官方指数。债券用中债-新综合财富指数；
          黄金用 COMEX 黄金连续（USD/oz）× USD/CNY 折算人民币/克，无分红。
          指数未扣产品费率，ETF 段扣 ETF 费率。
        </dd>
        <dt>历史不足</dt>
        <dd>
          请求的窗口长于该资产/相关矩阵实际可用的历史。系统会在样本月数旁
          标记“历史不足”，不会假装有完整窗口。当前 5/10/15 年窗口完整；
          全历史共同区间约从 2011 年开始，受上证指数 ETF 补长起点限制。
        </dd>
        <dt>应急金</dt>
        <dd>
          按 N 个月开销预留的现金桶。月结余先补足应急金，再投入金融资产；
          现金流缺口先用应急金，计划性事件默认先用投资资产。
        </dd>
        <dt>成长/防御组</dt>
        <dd>
          多资产策略把资产分成成长、防御和现金。随年龄下降的是成长组的
          总权重，组内比例保持不变。
        </dd>
        <dt>买入失败</dt>
        <dd>
          买房/买车的首付和费用不足时，该路径不会强行买入，也不强制赎回，
          只记录为未通过；一次性支出不足时才会赎回全部可用资产。
        </dd>
        <dt>run_id</dt>
        <dd>
          一次运行的内容哈希，由假设集、数据版本、代码指纹、随机种子和解释模式共同决定。
          相同 run_id 表示同一组输入和同一版代码。
        </dd>
      </dl>
    </details>
  )
}
